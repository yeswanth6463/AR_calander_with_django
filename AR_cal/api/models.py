from django.conf import settings
from django.db import models
from django.contrib.auth.models import AbstractUser
from django.utils.text import slugify
import uuid


class User(AbstractUser):
    email = models.EmailField(unique=True)
    phone_number = models.CharField(
        max_length=20,
        blank=True,
        null=True,
    )
    profile_image = models.ImageField(
        upload_to="profile_images/",
        blank=True,
        null=True,
    )
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return self.email

class Project(models.Model):
    STATUS_CHOICES = [
        ("draft", "Draft"),
        ("published", "Published"),
        ("archived", "Archived"),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="projects",
    )
    name = models.CharField(max_length=150)
    description = models.TextField(blank=True)
    slug = models.SlugField(max_length=180, unique=True, blank=True)
    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default="draft",
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-created_at"]

    def save(self, *args, **kwargs):
        if not self.slug:
            self.slug = slugify(self.name)

        super().save(*args, **kwargs)

    def __str__(self):
        return self.name


class TargetImage(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    project = models.ForeignKey(
        Project,
        on_delete=models.CASCADE,
        related_name="target_images",
    )

    name = models.CharField(max_length=150)

    image = models.ImageField(
        upload_to="target_images/"
    )

    # Information used by the image-tracking system
    target_width = models.FloatField(
        default=1.0,
        help_text="Physical width used for AR tracking/reference.",
    )

    target_height = models.FloatField(
        default=1.0,
        help_text="Physical height used for AR tracking/reference.",
    )

    tracking_data = models.JSONField(
        blank=True,
        null=True,
        help_text="Tracking/recognition metadata generated by the AR system.",
    )

    is_active = models.BooleanField(default=True)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.project.name} - {self.name}"


class ModelAsset(models.Model):
    FORMAT_CHOICES = [
        ("glb", "GLB"),
        ("gltf", "GLTF"),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    project = models.ForeignKey(
        Project,
        on_delete=models.CASCADE,
        related_name="models",
    )

    name = models.CharField(max_length=150)

    model_file = models.FileField(
        upload_to="models/"
    )

    thumbnail = models.ImageField(
        upload_to="model_thumbnails/",
        blank=True,
        null=True,
    )

    format = models.CharField(
        max_length=10,
        choices=FORMAT_CHOICES,
        blank=True,
    )

    file_size = models.BigIntegerField(
        blank=True,
        null=True,
        help_text="File size in bytes.",
    )

    has_animation = models.BooleanField(default=False)

    animation_count = models.PositiveIntegerField(default=0)

    animations = models.JSONField(
        blank=True,
        null=True,
        help_text="Animation names and metadata extracted from the 3D model.",
    )

    metadata = models.JSONField(
        blank=True,
        null=True,
        help_text="Additional model metadata.",
    )

    is_active = models.BooleanField(default=True)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.project.name} - {self.name}"


class ARExperience(models.Model):
    STATUS_CHOICES = [
        ("draft", "Draft"),
        ("ready", "Ready"),
        ("published", "Published"),
    ]

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    project = models.OneToOneField(
        Project,
        on_delete=models.CASCADE,
        related_name="ar_experience",
    )

    target_image = models.ForeignKey(
        TargetImage,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="ar_experiences",
    )

    model_asset = models.ForeignKey(
        ModelAsset,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="ar_experiences",
    )

    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default="draft",
    )

    # 3D placement configuration
    position_x = models.FloatField(default=0.0)
    position_y = models.FloatField(default=0.0)
    position_z = models.FloatField(default=0.0)

    rotation_x = models.FloatField(default=0.0)
    rotation_y = models.FloatField(default=0.0)
    rotation_z = models.FloatField(default=0.0)

    scale = models.FloatField(default=1.0)

    # Additional AR configuration
    settings = models.JSONField(
        blank=True,
        null=True,
        help_text="Additional AR experience configuration.",
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"AR Experience - {self.project.name}"


class PublishedExperience(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    experience = models.OneToOneField(
        ARExperience,
        on_delete=models.CASCADE,
        related_name="published_experience",
    )

    public_id = models.UUIDField(
        default=uuid.uuid4,
        unique=True,
        editable=False,
    )

    version = models.PositiveIntegerField(default=1)

    is_active = models.BooleanField(default=True)

    published_at = models.DateTimeField(auto_now_add=True)

    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"Published - {self.experience.project.name}"


class QRCode(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    published_experience = models.OneToOneField(
        PublishedExperience,
        on_delete=models.CASCADE,
        related_name="qr_code",
    )

    qr_image = models.ImageField(
        upload_to="qr_codes/",
        blank=True,
        null=True,
    )

    public_url = models.URLField(max_length=500)

    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"QR - {self.published_experience.experience.project.name}"